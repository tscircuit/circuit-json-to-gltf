import { test, expect } from "bun:test"
import { loadSTL } from "../../lib"

const buildBinaryStl = (
  headerText: string,
  triangles: Array<{
    normal: [number, number, number]
    vertices: [number, number, number][]
  }>,
): ArrayBuffer => {
  const buffer = new ArrayBuffer(84 + 50 * triangles.length)
  const bytes = new Uint8Array(buffer)
  bytes.set(new TextEncoder().encode(headerText.slice(0, 80)))

  const view = new DataView(buffer)
  view.setUint32(80, triangles.length, true)

  triangles.forEach((triangle, index) => {
    let offset = 84 + index * 50
    for (const component of triangle.normal) {
      view.setFloat32(offset, component, true)
      offset += 4
    }
    for (const vertex of triangle.vertices) {
      for (const component of vertex) {
        view.setFloat32(offset, component, true)
        offset += 4
      }
    }
  })

  return buffer
}

const withStubbedFetch = async (
  body: BodyInit,
  run: () => Promise<void>,
): Promise<void> => {
  const originalFetch = globalThis.fetch
  globalThis.fetch = (async () => new Response(body)) as unknown as typeof fetch
  try {
    await run()
  } finally {
    globalThis.fetch = originalFetch
  }
}

// Binary STL writers may legally put any text in the 80-byte header, including
// the word "solid" (old SolidWorks exports are the well-known case). The file
// must be detected as binary anyway, not fed to the ASCII parser, which finds
// no "facet" keywords and silently returns an empty mesh.
test("parses a binary STL whose header begins with 'solid'", async () => {
  const stl = buildBinaryStl("solid generated by a binary writer", [
    {
      normal: [0, 0, 1],
      vertices: [
        [0, 0, 0],
        [1, 0, 0],
        [1, 1, 0],
      ],
    },
    {
      normal: [0, 0, 1],
      vertices: [
        [0, 0, 0],
        [1, 1, 0],
        [0, 1, 0],
      ],
    },
  ])

  await withStubbedFetch(stl, async () => {
    const mesh = await loadSTL({
      url: "https://models.test/binary-solid-header.stl",
      transform: {},
    })
    expect(mesh.triangles).toHaveLength(2)
    expect(mesh.triangles[0]!.vertices[1]).toEqual({ x: 1, y: 0, z: 0 })
    expect(mesh.triangles[1]!.vertices[2]).toEqual({ x: 0, y: 1, z: 0 })
  })
})

test("still parses an ASCII STL that begins with 'solid'", async () => {
  const asciiStl = `solid triangle
  facet normal 0 0 1
    outer loop
      vertex 0 0 0
      vertex 2 0 0
      vertex 0 2 0
    endloop
  endfacet
endsolid triangle
`

  await withStubbedFetch(new TextEncoder().encode(asciiStl), async () => {
    const mesh = await loadSTL({
      url: "https://models.test/ascii-solid-header.stl",
      transform: {},
    })
    expect(mesh.triangles).toHaveLength(1)
    expect(mesh.triangles[0]!.vertices[1]).toEqual({ x: 2, y: 0, z: 0 })
  })
})
